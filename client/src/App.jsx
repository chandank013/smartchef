import { useState, useCallback, useMemo } from 'react';
import useLocalStorage from './hooks/useLocalStorage';
import useRecipeApi from './hooks/useRecipeApi';
import Header from './components/Header';
import IngredientForm from './components/IngredientForm';
import ExploreBar from './components/ExploreBar';
import RecipeCard from './components/RecipeCard';
import RecipeDetails from './components/RecipeDetails';
import { Empty, Loading, ErrorState } from './components/States';
import {
  keyOf,
  CURATED_EXPLORE_RECIPES,
  filterAndSortRecipes,
} from './lib';

const sameQ = (a, b) =>
  a.ingredients.join() === b.ingredients.join() &&
  a.diet === b.diet &&
  a.servings === b.servings;

export default function App() {
  const [view, setView] = useState('results'); // Default to Explore view as requested
  const [search, setSearch] = useLocalStorage('sc:search', null); // { query, recipes }
  const [history, setHistory] = useLocalStorage('sc:history', []); // last 5 searches
  const [favs, setFavs] = useLocalStorage('sc:favorites', []);
  const [req, setReq] = useState(null);
  const [open, setOpen] = useState(null);
  const api = useRecipeApi();
  const close = useCallback(() => setOpen(null), []);

  // Explore page filter states
  const [searchQuery, setSearchQuery] = useState('');
  const [selectedDiet, setSelectedDiet] = useState('any');
  const [selectedTime, setSelectedTime] = useState('any');
  const [selectedCalories, setSelectedCalories] = useState('any');
  const [selectedCategory, setSelectedCategory] = useState('All Recipes');
  const [sortBy, setSortBy] = useState('relevant');

  const run = async (q) => {
    setReq(q);
    setView('results');
    const recipes = await api.generate(q);
    if (recipes && recipes.length) {
      setSearch({ query: q, recipes });
      setHistory((h) => [q, ...h.filter((x) => !sameQ(x, q))].slice(0, 5));
    }
  };

  const handleExploreSearchSubmit = () => {
    if (!searchQuery.trim()) return;
    // If user enters comma-separated ingredients or search terms, trigger AI generation
    const rawList = searchQuery
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean);
    if (rawList.length) {
      run({
        ingredients: rawList,
        diet: selectedDiet,
        servings: 2,
      });
    }
  };

  const isSaved = (r) => favs.some((f) => keyOf(f) === keyOf(r));
  const toggle = (r, diet = 'any', servings = 2) =>
    setFavs((f) =>
      f.some((x) => keyOf(x) === keyOf(r))
        ? f.filter((x) => keyOf(x) !== keyOf(r))
        : [{ ...r, diet, servings }, ...f]
    );

  const q = req || search?.query;

  // Combine curated explore recipes with any recipes generated by the user
  const baseExploreRecipes = useMemo(() => {
    const aiGenerated = search?.recipes || [];
    // Deduplicate recipes by title
    const seen = new Set();
    const combined = [];
    for (const r of [...aiGenerated, ...CURATED_EXPLORE_RECIPES]) {
      const k = keyOf(r);
      if (!seen.has(k)) {
        seen.add(k);
        combined.push(r);
      }
    }
    return combined;
  }, [search]);

  // Compute filtered & sorted recipes for Explore view
  const displayRecipes = useMemo(() => {
    return filterAndSortRecipes(baseExploreRecipes, {
      search: searchQuery,
      category: selectedCategory,
      diet: selectedDiet,
      time: selectedTime,
      calories: selectedCalories,
      sortBy,
    });
  }, [
    baseExploreRecipes,
    searchQuery,
    selectedCategory,
    selectedDiet,
    selectedTime,
    selectedCalories,
    sortBy,
  ]);

  return (
    <>
      <Header view={view} setView={setView} favCount={favs.length} />
      <main className="wrap">
        {/* 1. Home View */}
        {view === 'home' && (
          <IngredientForm
            initial={q}
            history={history}
            busy={api.loading}
            onSubmit={run}
            onPick={run}
          />
        )}

        {/* 2. Explore / Recipe Results View */}
        {view === 'results' && (
          <section aria-label="Explore Recipes">
            <ExploreBar
              searchQuery={searchQuery}
              onSearchQueryChange={setSearchQuery}
              selectedDiet={selectedDiet}
              onDietChange={setSelectedDiet}
              selectedTime={selectedTime}
              onTimeChange={setSelectedTime}
              selectedCalories={selectedCalories}
              onCaloriesChange={setSelectedCalories}
              selectedCategory={selectedCategory}
              onCategoryChange={setSelectedCategory}
              sortBy={sortBy}
              onSortChange={setSortBy}
              onSearchSubmit={handleExploreSearchSubmit}
              busy={api.loading}
            />

            {api.loading ? (
              <Loading />
            ) : api.error ? (
              <ErrorState
                message={api.error}
                onRetry={() => (req ? run(req) : handleExploreSearchSubmit())}
                onBack={() => setView('home')}
              />
            ) : !displayRecipes.length ? (
              <Empty
                title="No recipes found"
                text="Try adjusting your search terms or clearing some filters to discover more recipes."
                action="Reset Filters"
                onAction={() => {
                  setSearchQuery('');
                  setSelectedDiet('any');
                  setSelectedTime('any');
                  setSelectedCalories('any');
                  setSelectedCategory('All Recipes');
                }}
              />
            ) : (
              <div className="explore-grid">
                {displayRecipes.map((r) => {
                  const dietType = r.diet || (search?.query?.diet) || 'any';
                  const srv = r.servings || (search?.query?.servings) || 2;
                  return (
                    <RecipeCard
                      key={keyOf(r)}
                      mode="explore"
                      recipe={r}
                      diet={dietType}
                      saved={isSaved(r)}
                      onToggle={() => toggle(r, dietType, srv)}
                      onView={() =>
                        setOpen({
                          recipe: r,
                          diet: dietType,
                          servings: srv,
                        })
                      }
                    />
                  );
                })}
              </div>
            )}
          </section>
        )}

        {/* 3. Favorites View */}
        {view === 'favorites' && (
          <section aria-labelledby="ft">
            <div className="head">
              <div>
                <h2 id="ft">
                  <span className="red">♥</span> Your Favorite Recipes
                </h2>
                <p className="muted">
                  Recipes you've saved will appear here. You can remove them anytime.
                </p>
              </div>
            </div>
            {!favs.length ? (
              <Empty
                title="No favorites yet"
                text="Tap the heart on any recipe to save it here."
                action="Explore Recipes"
                onAction={() => setView('results')}
              />
            ) : (
              <div className="explore-grid">
                {favs.map((r) => (
                  <RecipeCard
                    key={keyOf(r)}
                    mode="favorites"
                    recipe={r}
                    diet={r.diet}
                    saved
                    onToggle={() => toggle(r)}
                    onView={() =>
                      setOpen({
                        recipe: r,
                        diet: r.diet,
                        servings: r.servings || 2,
                      })
                    }
                  />
                ))}
              </div>
            )}
          </section>
        )}
      </main>

      {/* Recipe Details Modal Dialog */}
      {open && (
        <RecipeDetails
          recipe={open.recipe}
          diet={open.diet}
          servings={open.servings}
          saved={isSaved(open.recipe)}
          onToggle={() => toggle(open.recipe, open.diet, open.servings)}
          onClose={close}
        />
      )}
    </>
  );
}
